#!/usr/bin/env python3
"""Generate a kernel include/generated/autoconf.h from a resolved .config.

Used to build a *layout probe* TU with the Android NDK clang, so struct
offsets can be extracted without a Linux host / full kernel build.
"""
import gzip
import os
import re
import sys

def main(cfg_path, outdir):
    if cfg_path.endswith('.gz'):
        data = gzip.open(cfg_path, 'rt', errors='replace').read()
    else:
        data = open(cfg_path, 'r', errors='replace').read()

    gen = os.path.join(outdir, 'include', 'generated')
    os.makedirs(gen, exist_ok=True)
    os.makedirs(os.path.join(outdir, 'include', 'config'), exist_ok=True)

    defines = []
    autoconf = []
    for line in data.splitlines():
        line = line.strip()
        m = re.match(r'^(CONFIG_[A-Za-z0-9_]+)=(.*)$', line)
        if m:
            name, val = m.group(1), m.group(2)
            if val == 'y':
                autoconf.append('#define %s 1' % name)
                defines.append('%s=y' % name)
            elif val == 'm':
                autoconf.append('#define %s_MODULE 1' % name)
                autoconf.append('#define %s 1' % name)
                defines.append('%s=m' % name)
            elif val.startswith('"'):
                autoconf.append('#define %s %s' % (name, val))
                defines.append('%s=%s' % (name, val))
            else:
                autoconf.append('#define %s %s' % (name, val))
                defines.append('%s=%s' % (name, val))
        elif line.startswith('# CONFIG_') and line.endswith(' is not set'):
            name = line[2:].split(' ')[0]
            autoconf.append('/* #undef %s */' % name)

    with open(os.path.join(gen, 'autoconf.h'), 'w', newline='\n') as f:
        f.write('/* generated by gen_autoconf.py */\n')
        f.write('\n'.join(autoconf) + '\n')
    with open(os.path.join(outdir, 'include', 'config', 'auto.conf'), 'w', newline='\n') as f:
        f.write('\n'.join(defines) + '\n')

    # utsrelease.h: localversion comes from the device banner (4.19.113-25305888)
    localver = os.environ.get('KBUILD_LOCALVERSION', '-25305888')
    with open(os.path.join(gen, 'utsrelease.h'), 'w', newline='\n') as f:
        f.write('#define UTS_RELEASE "4.19.113%s"\n' % localver)
    with open(os.path.join(gen, 'compile.h'), 'w', newline='\n') as f:
        f.write('#define UTS_VERSION "#1 SMP PREEMPT"\n')
        f.write('#define LINUX_COMPILE_BY "builder"\n')
        f.write('#define LINUX_COMPILE_HOST "builder"\n')
        f.write('#define LINUX_COMPILER "clang version 10.0.6"\n')

    # bounds.h must exist for <linux/bounds.h>; values are only used by asm() code
    with open(os.path.join(gen, 'bounds.h'), 'w', newline='\n') as f:
        f.write('#ifndef __LINUX_BOUNDS_H__\n#define __LINUX_BOUNDS_H__\n')
        f.write('#define NR_PAGEFLAGS 24\n#define MAX_NR_ZONES 4\n')
        f.write('#define NR_PAGE_TYPE 8\n')
        f.write('#endif\n')

    print('autoconf.h: %d defines -> %s' % (len(autoconf), gen))

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else '.')
